    @Test
    internal func testSignedEnvelopeStructure() throws {
        let transaction = try makeEnvelopeTransaction()
        // The sender signs for itself. Any other account would be a rekeyed signer, and the
        // envelope would (correctly) carry `sgnr` as a third key.
        let seed = try hexData("14a16b7d74ba2c495533d743658ee19bc27300ce302a4f19f3bb766a3c8cb02e")
        let account = try Account(privateKey: seed)
        #expect(account.address == transaction.sender)
        let signed = try SignedTransaction.sign(transaction, with: account)
        let encoded = try signed.encode()

        // 0x82 fixmap(2), "sig", bin8(64)
        #expect(encoded.prefix(7).hexString == "82a3736967c440")
        #expect(encoded.count == 241)

        // The embedded txn must be byte-identical to the standalone encoding.
        let unsigned = try transaction.encode(groupID: nil)
        #expect(unsigned.hexString == Self.signedEnvelopeUnsignedTxnHex)
        #expect(encoded.suffix(unsigned.count + 4).hexString == "a374786e" + unsigned.hexString)

        // The signature must verify over "TX" + encoded, whatever its bytes.
        #expect(account.verify(signature: signed.signature, for: Data("TX".utf8) + unsigned))
    }

    /// On a deterministic Ed25519 backend the whole envelope is byte-exact. This test is a no-op
    /// on Darwin, where CryptoKit's randomized nonce makes the signature unreproducible.
    @Test(
        .enabled(
            if: CanonicalEncodingTests.ed25519SignaturesAreDeterministic,
            "CryptoKit randomizes the Ed25519 nonce; signature bytes are not reproducible on Darwin."
        )
    )
    internal func testSignedEnvelopeIsByteExactOnDeterministicBackends() throws {
        let transaction = try makeEnvelopeTransaction()
        let seed = try hexData("14a16b7d74ba2c495533d743658ee19bc27300ce302a4f19f3bb766a3c8cb02e")
        let account = try Account(privateKey: seed)
        let signed = try SignedTransaction.sign(transaction, with: account)
        let encoded = try signed.encode()

        #expect(signed.signature.hexString == Self.signedEnvelopeSignatureHex)
        #expect(encoded.hexString == Self.signedEnvelopeHex)
    }
