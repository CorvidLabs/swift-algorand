// MARK: - Hex helpers

internal enum CanonicalVectorError: Error, CustomStringConvertible {
    case invalidHex(String)

    internal var description: String {
        switch self {
        case .invalidHex(let value): return "Not a valid hex string: \(value)"
        }
    }
}

/// Decodes a lowercase hex string into `Data`, throwing rather than force-unwrapping.
internal func hexData(_ string: String) throws -> Data {
    guard string.count % 2 == 0 else {
        throw CanonicalVectorError.invalidHex(string)
    }

    var bytes = [UInt8]()
    bytes.reserveCapacity(string.count / 2)

    var index = string.startIndex
    while index < string.endIndex {
        let next = string.index(index, offsetBy: 2)
        guard let byte = UInt8(string[index..<next], radix: 16) else {
            throw CanonicalVectorError.invalidHex(string)
        }
        bytes.append(byte)
        index = next
    }

    return Data(bytes)
}

extension Data {
    /// Lowercase hex, so failures print a diff a human can read.
    internal var hexString: String {
        map { String(format: "%02x", $0) }.joined()
    }

    /// Whether this data contains `subsequence` anywhere.
    internal func containsSubsequence(_ subsequence: Data) -> Bool {
        guard !subsequence.isEmpty, subsequence.count <= count else {
            return false
        }

        let selfBytes = Array(self)
        let needle = Array(subsequence)
        for start in 0...(selfBytes.count - needle.count) where
            Array(selfBytes[start..<(start + needle.count)]) == needle {
            return true
        }
        return false
    }
}
