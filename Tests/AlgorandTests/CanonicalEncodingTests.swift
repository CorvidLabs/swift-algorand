    // MARK: - Assertions

    /// Asserts that a transaction encodes to exactly `encodesTo` and hashes to exactly `txID`.
    /// Failures are attributed to the calling test through `sourceLocation`.
    internal func assertCanonical(
        _ transaction: any Transaction,
        groupID: Data? = nil,
        encodesTo expectedHex: String,
        txID expectedTxID: String,
        sourceLocation: SourceLocation = #_sourceLocation
    ) throws {
        let encoded = try transaction.encode(groupID: groupID)
        #expect(
            encoded.hexString == expectedHex,
            "canonical msgpack bytes differ from the golden vector",
            sourceLocation: sourceLocation
        )
        #expect(
            Self.transactionID(forEncoded: encoded) == expectedTxID,
            "transaction ID differs from the golden vector",
            sourceLocation: sourceLocation
        )
    }

    /// Computes a transaction ID the way the network does: base32(SHA512-256("TX" + encoded)).
    internal static func transactionID(forEncoded encoded: Data) -> String {
        let prefixed = Data("TX".utf8) + encoded
        return SHA512_256.hash(data: prefixed).base32EncodedString()
    }

