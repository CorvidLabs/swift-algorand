/**
 Golden-vector conformance suite for the canonical MessagePack encoder.

 Every assertion in this file is BYTE EQUALITY against a hex literal, plus the
 transaction ID that the network computes from those bytes. That is the whole
 point: the pre-existing encoding tests assert only `encoded.count > 0` or that
 some substring is present, which cannot distinguish a correct encoder from a
 differently-wrong one.

 ## Where the expected bytes come from

 The vectors were generated by a script that implements go-algorand's
 msgp-generated marshalling semantics directly -- `_struct codec:",omitempty,
 omitemptyarray"`, meaning every field is dropped when it holds its zero value
 -- and then cross-checked byte-for-byte against py-algorand-sdk 2.12.0 (MIT).
 go-algorand v5.0.1-stable is the authority where the two disagree; the three
 places they do disagree are documented on the individual tests.

 No fixture file was copied from any Algorand repository. py-algorand-sdk
 vendors post-quantum fixtures under `tests/unit_tests/pq_test_data/`, but
 `lsig_address_kat.json` originates in `algorandfoundation/falcon-signatures`
 (AGPL-3.0) and the `pq*.json` files originate in
 `algorandfoundation/algokit-polytest`, which publishes no licence at all.
 Neither is safe to port into an MIT package, so the post-quantum vectors here
 are regenerated from first principles.

 ## Fixtures

 Accounts are derived deterministically from fixed labels, so the vectors can
 be regenerated at any time. The network parameters are TestNet's real genesis
 ID and hash.
 */

